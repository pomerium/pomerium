package cryptutil_test

import (
	"bytes"
	"testing"

	"github.com/stretchr/testify/assert"

	"github.com/pomerium/pomerium/pkg/cryptutil"
)

func TestDeriveKey(t *testing.T) {
	t.Parallel()

	key := cryptutil.DeriveKey(bytes.Repeat([]byte{0x01}, 32), "test")
	assert.Equal(t, []byte{
		0x9f, 0x6d, 0xfa, 0x74, 0x81, 0xf0, 0x81, 0x03, 0xd9, 0xdf, 0xcc, 0x84, 0x6e, 0x99, 0x74, 0xe4,
		0x74, 0x72, 0xf9, 0xd7, 0x93, 0x5c, 0x99, 0x65, 0x69, 0xcd, 0x6d, 0x5c, 0xe8, 0x17, 0x91, 0xe1,
	}, key)
}
